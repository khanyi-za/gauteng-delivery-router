-- Orders that customers have placed. "order" is a reserved word in SQL, so the table is delivery_order.

CREATE TABLE delivery_order (
                                id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                store_id     BIGINT           NOT NULL REFERENCES store (id),
                                customer_lat DOUBLE PRECISION NOT NULL,
                                customer_lon DOUBLE PRECISION NOT NULL,
                                status       VARCHAR(20)      NOT NULL,
                                placed_at    TIMESTAMPTZ      NOT NULL,
                                deliver_by   TIMESTAMPTZ      NOT NULL,
                                drive_time_s DOUBLE PRECISION NOT NULL -- from the store to the customer, worked out when the order was placed
);

-- What's in each order: one row per product
CREATE TABLE order_item (
                            order_id BIGINT      NOT NULL REFERENCES delivery_order (id),
                            sku      VARCHAR(32) NOT NULL REFERENCES product (sku),
                            quantity INTEGER     NOT NULL CHECK (quantity > 0),
                            PRIMARY KEY (order_id, sku)
);

CREATE INDEX idx_delivery_order_status ON delivery_order (status);
