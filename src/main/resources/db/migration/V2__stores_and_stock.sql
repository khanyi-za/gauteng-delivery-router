-- The fictional retailer's stores, the products it sells, and how many of each product each store has.

CREATE TABLE store (
                       id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(100)     NOT NULL UNIQUE,
                       lat  DOUBLE PRECISION NOT NULL,
                       lon  DOUBLE PRECISION NOT NULL
);

CREATE TABLE product (
                         sku  VARCHAR(32) PRIMARY KEY, -- stock-keeping unit: the retailer's own product code
                         name VARCHAR(100) NOT NULL
);

-- One row per store and product
CREATE TABLE store_stock (
                             id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             store_id BIGINT      NOT NULL REFERENCES store (id),
                             sku      VARCHAR(32) NOT NULL REFERENCES product (sku),
                             quantity INTEGER     NOT NULL CHECK (quantity >= 0),
                             version  BIGINT      NOT NULL DEFAULT 0, -- goes up by one on every change, so two changes at once can't both win
                             UNIQUE (store_id, sku)
);

CREATE INDEX idx_store_stock_sku ON store_stock (sku);