-- The drivers who deliver orders. Each one works from one store.

CREATE TABLE driver (
                        id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        store_id BIGINT       NOT NULL REFERENCES store (id),
                        name     VARCHAR(100) NOT NULL,
                        free_at  TIMESTAMPTZ  NOT NULL DEFAULT now() -- when they're next back at the store, ready for another delivery
);

-- Which driver took each order, and when
ALTER TABLE delivery_order
    ADD COLUMN driver_id     BIGINT REFERENCES driver (id),
    ADD COLUMN dispatched_at TIMESTAMPTZ, -- when the driver left the store
    ADD COLUMN delivered_at  TIMESTAMPTZ; -- when the driver reaches (or reached) the customer